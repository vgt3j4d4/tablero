#!/usr/bin/env python3
"""Generates the launcher art as vector drawables: the Android TV banner and the adaptive icon's layers.

Design A from docs/design/icons.html. The banner is the game clock as it reads on the board (red DSEG7 digits over
their unlit "8" ghosts, in the clock box) above the TABLERO wordmark in Barlow Condensed. The icon is one
seven-segment "t" over its ghost "8". Text is drawn as glyph outlines taken from the app's own fonts, so the
drawables need no font at runtime; the font files themselves are left untouched.

Tune the constants below, run the script again and check the result on the stick. Needs fontTools and HarfBuzz:

    pip install fonttools uharfbuzz
    python3 scripts/make-icons.py
"""

from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "tv-app/src/main/res"
FONTS = ROOT / "tv-app/src/main/assets/fonts"
LED_FONT = FONTS / "DSEG7Classic-Bold.ttf"
WORDMARK_FONT = FONTS / "BarlowCondensed-ExtraBold.ttf"
BANNER_OUTPUT = RES / "drawable/banner.xml"
ICON_OUTPUT = RES / "drawable/ic_launcher_foreground.xml"
MONOCHROME_OUTPUT = RES / "drawable/ic_launcher_monochrome.xml"

# Banner, 320×180 (the size Android TV requires). Baselines and centers in viewport units.
BANNER_WIDTH = 320
BANNER_HEIGHT = 180
# The panel grey rather than the board's black: the stock launcher's background is black too, and an unfocused tile
# would lose its edge.
BANNER_BACKGROUND = "@color/panel"
CLOCK_BOX = (44, 20, 232, 92)  # x, y, width, height
CLOCK_BOX_RADIUS = 12
CLOCK_BOX_STROKE = 1.5
CLOCK_TEXT = "10:00"
CLOCK_GHOST = "88:88"
CLOCK_SIZE = 50
CLOCK_BASELINE = 89
WORDMARK_TEXT = "TABLERO"
WORDMARK_SIZE = 40
WORDMARK_TRACKING = 7
WORDMARK_BASELINE = 160

# Adaptive icon foreground, 108×108 with the 66 safe zone centered. The ghost "8" is centered in the viewport and
# sized so its diagonal just fits the safe zone; the lit glyph sits on the same origin.
ICON_SIZE = 108
ICON_GLYPH = "t"
ICON_GHOST = "8"
ICON_GLYPH_SIZE = 56

DECIMALS = 2
HEADER = "Generated by scripts/make-icons.py from the app's fonts; edit the script, not this file."


class Font:
    """A font file that lays out a line of text (HarfBuzz, so kerning applies) and returns it as path data."""

    def __init__(self, path: Path) -> None:
        self.tt = TTFont(path)
        self.glyphs = self.tt.getGlyphSet()
        self.upem = self.tt["head"].unitsPerEm
        self.hb_font = hb.Font(hb.Face(hb.Blob.from_file_path(str(path))))

    def _shape(self, text: str) -> list[tuple[str, int, int, int]]:
        buffer = hb.Buffer()
        buffer.add_str(text)
        buffer.guess_segment_properties()
        hb.shape(self.hb_font, buffer)
        return [
            (self.tt.getGlyphName(info.codepoint), pos.x_advance, pos.x_offset, pos.y_offset)
            for info, pos in zip(buffer.glyph_infos, buffer.glyph_positions)
        ]

    def width(self, text: str, size: float, tracking: float = 0) -> float:
        """Advance width of [text] at [size], with [tracking] between glyphs (not after the last one)."""
        shaped = self._shape(text)
        return sum(advance for _, advance, _, _ in shaped) * size / self.upem + tracking * (len(shaped) - 1)

    def path(self, text: str, size: float, x: float, baseline: float, tracking: float = 0) -> str:
        """Outlines of [text] starting at [x] on [baseline], y pointing down as in the drawable's viewport."""
        scale = size / self.upem
        pen = SVGPathPen(self.glyphs, ntos=number)
        cursor = x
        for name, advance, x_offset, y_offset in self._shape(text):
            origin = (cursor + x_offset * scale, baseline - y_offset * scale)
            self.glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, *origin)))
            cursor += advance * scale + tracking
        return pen.getCommands()

    def centered_path(self, text: str, size: float, center_x: float, baseline: float, tracking: float = 0) -> str:
        return self.path(text, size, center_x - self.width(text, size, tracking) / 2, baseline, tracking)


def number(value: float) -> str:
    text = f"{value:.{DECIMALS}f}".rstrip("0").rstrip(".")
    return "0" if text == "-0" else text


def rounded_rect(x: float, y: float, width: float, height: float, radius: float) -> str:
    r = radius
    return (
        f"M{number(x + r)},{number(y)}h{number(width - 2 * r)}a{r},{r} 0 0 1 {r},{r}v{number(height - 2 * r)}"
        f"a{r},{r} 0 0 1 -{r},{r}h-{number(width - 2 * r)}a{r},{r} 0 0 1 -{r},-{r}v-{number(height - 2 * r)}"
        f"a{r},{r} 0 0 1 {r},-{r}z"
    )


def path(data: str, fill: str | None = None, stroke: str | None = None, stroke_width: float | None = None) -> str:
    attributes = []
    if fill:
        attributes.append(f'android:fillColor="{fill}"')
    if stroke:
        attributes.append(f'android:strokeColor="{stroke}"')
        attributes.append(f'android:strokeWidth="{number(stroke_width)}"')
    attributes.append(f'android:pathData="{data}"')
    return "    <path\n" + "".join(f"        {a}\n" for a in attributes[:-1]) + f"        {attributes[-1]} />\n"


def vector(width: int, height: int, paths: list[str], comment: str, ignore: str | None = None) -> str:
    tools_ns = '\n    xmlns:tools="http://schemas.android.com/tools"' if ignore else ""
    tools_ignore = f'\n    tools:ignore="{ignore}"' if ignore else ""
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!--\n  {comment}\n  {HEADER}\n-->\n"
        f'<vector xmlns:android="http://schemas.android.com/apk/res/android"{tools_ns}\n'
        f'    android:width="{width}dp"\n'
        f'    android:height="{height}dp"\n'
        f'    android:viewportWidth="{width}"\n'
        f'    android:viewportHeight="{height}"{tools_ignore}>\n'
        + "".join(paths)
        + "</vector>\n"
    )


def banner(led: Font, wordmark: Font) -> str:
    center = BANNER_WIDTH / 2
    paths = [
        path(f"M0,0h{BANNER_WIDTH}v{BANNER_HEIGHT}h-{BANNER_WIDTH}z", fill=BANNER_BACKGROUND),
        path(
            rounded_rect(*CLOCK_BOX, CLOCK_BOX_RADIUS),
            fill="@color/clock_box",
            stroke="@color/clock_box_border",
            stroke_width=CLOCK_BOX_STROKE,
        ),
        path(led.centered_path(CLOCK_GHOST, CLOCK_SIZE, center, CLOCK_BASELINE), fill="@color/led_red_unlit_icon"),
        path(led.centered_path(CLOCK_TEXT, CLOCK_SIZE, center, CLOCK_BASELINE), fill="@color/led_red"),
        path(
            wordmark.centered_path(WORDMARK_TEXT, WORDMARK_SIZE, center, WORDMARK_BASELINE, WORDMARK_TRACKING),
            fill="@color/text",
        ),
    ]
    # VectorRaster, VectorPath: the banner is larger and its wordmark path longer than lint likes for vectors, but
    # the launcher draws it once.
    comment = "Android TV launcher banner: the LED game clock over the TABLERO wordmark (320×180, required size)."
    return vector(BANNER_WIDTH, BANNER_HEIGHT, paths, comment, ignore="VectorRaster,VectorPath")


def icon_origin(led: Font) -> tuple[float, float]:
    """Where the icon glyphs start: the ghost's ink box centered in the viewport, shared by the lit glyph."""
    bounds = BoundsPen(led.glyphs)
    led.glyphs[led.tt.getBestCmap()[ord(ICON_GHOST)]].draw(bounds)
    x_min, y_min, x_max, y_max = (v * ICON_GLYPH_SIZE / led.upem for v in bounds.bounds)
    return ICON_SIZE / 2 - (x_min + x_max) / 2, ICON_SIZE / 2 + (y_min + y_max) / 2


def icon_foreground(led: Font) -> str:
    x, baseline = icon_origin(led)
    paths = [
        path(led.path(ICON_GHOST, ICON_GLYPH_SIZE, x, baseline), fill="@color/led_red_unlit_icon"),
        path(led.path(ICON_GLYPH, ICON_GLYPH_SIZE, x, baseline), fill="@color/led_red"),
    ]
    comment = 'Adaptive icon foreground: a seven-segment "t" over its unlit "8", inside the 66 safe zone.'
    return vector(ICON_SIZE, ICON_SIZE, paths, comment)


def icon_monochrome(led: Font) -> str:
    # Themed icons tint this layer by its alpha, so it holds only the lit glyph; a ghost would light up too.
    x, baseline = icon_origin(led)
    paths = [path(led.path(ICON_GLYPH, ICON_GLYPH_SIZE, x, baseline), fill="#FFFFFFFF")]
    comment = 'Adaptive icon monochrome layer (themed icons): the lit "t" alone.'
    return vector(ICON_SIZE, ICON_SIZE, paths, comment)


def main() -> None:
    led = Font(LED_FONT)
    wordmark = Font(WORDMARK_FONT)
    BANNER_OUTPUT.write_text(banner(led, wordmark))
    ICON_OUTPUT.write_text(icon_foreground(led))
    MONOCHROME_OUTPUT.write_text(icon_monochrome(led))
    for output in (BANNER_OUTPUT, ICON_OUTPUT, MONOCHROME_OUTPUT):
        print(output.relative_to(ROOT))


if __name__ == "__main__":
    main()
